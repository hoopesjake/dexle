-- PokéConnections daily puzzle bank and server-authoritative player progress.
create table if not exists public.poke_connections_puzzles (
  id bigint generated by default as identity primary key,
  title text not null,
  groups jsonb not null check (jsonb_typeof(groups)='array' and jsonb_array_length(groups)=4),
  card_order integer[] not null,
  created_at timestamptz not null default now()
);

create table if not exists public.poke_connections_results (
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_date date not null,
  puzzle_id bigint not null references public.poke_connections_puzzles(id),
  solved_tiers text[] not null default '{}',
  mistakes smallint not null default 0 check (mistakes between 0 and 4),
  completed boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (user_id,challenge_date)
);

alter table public.poke_connections_puzzles enable row level security;
alter table public.poke_connections_results enable row level security;
