create or replace function public.poke_connections_today()
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_user uuid:=auth.uid(); v_date date:=(now() at time zone 'America/Denver')::date;
  v_count integer; v_puzzle public.poke_connections_puzzles%rowtype;
  v_result public.poke_connections_results%rowtype; v_cards jsonb; v_groups jsonb;
begin
  if v_user is null then raise exception 'Sign-in required'; end if;
  select count(*) into v_count from public.poke_connections_puzzles;
  if v_count=0 then raise exception 'No PokéConnections puzzles are installed'; end if;
  select * into v_puzzle from public.poke_connections_puzzles
    order by id offset mod(v_date-date '2026-01-01',v_count) limit 1;
  insert into public.poke_connections_results(user_id,challenge_date,puzzle_id)
    values(v_user,v_date,v_puzzle.id) on conflict do nothing;
  select * into v_result from public.poke_connections_results
    where user_id=v_user and challenge_date=v_date;
  select jsonb_agg(card order by array_position(v_puzzle.card_order,(card->>'id')::integer)) into v_cards
    from jsonb_array_elements(v_puzzle.groups) grp
    cross join lateral jsonb_array_elements(grp->'pokemon') card;
  if v_result.mistakes>=4 then v_groups:=v_puzzle.groups;
  else
    select coalesce(jsonb_agg(grp order by array_position(v_result.solved_tiers,grp->>'tier')),'[]'::jsonb)
      into v_groups from jsonb_array_elements(v_puzzle.groups) grp
      where grp->>'tier'=any(v_result.solved_tiers);
  end if;
  return jsonb_build_object('date',v_date,'title',v_puzzle.title,'cards',v_cards,
    'solved',v_groups,'mistakes',v_result.mistakes,'completed',v_result.completed,
    'won',cardinality(v_result.solved_tiers)=4,'solved_count',cardinality(v_result.solved_tiers));
end; $$;

create or replace function public.submit_poke_connections(p_ids integer[])
returns jsonb language plpgsql security definer set search_path='' as $$
declare
  v_user uuid:=auth.uid(); v_date date:=(now() at time zone 'America/Denver')::date;
  v_result public.poke_connections_results%rowtype; v_puzzle public.poke_connections_puzzles%rowtype;
  v_match jsonb; v_ids integer[];
begin
  if v_user is null then raise exception 'Sign-in required'; end if;
  select array_agg(x order by x) into v_ids from (select distinct unnest(p_ids) x) q;
  if cardinality(v_ids)<>4 then raise exception 'Select exactly four different Pokémon'; end if;
  select * into v_result from public.poke_connections_results
    where user_id=v_user and challenge_date=v_date for update;
  if not found then perform public.poke_connections_today(); select * into v_result
    from public.poke_connections_results where user_id=v_user and challenge_date=v_date for update; end if;
  if v_result.completed then return public.poke_connections_today(); end if;
  select * into v_puzzle from public.poke_connections_puzzles where id=v_result.puzzle_id;
  select grp into v_match from jsonb_array_elements(v_puzzle.groups) grp
    where not (grp->>'tier'=any(v_result.solved_tiers)) and
      (select array_agg((mon->>'id')::integer order by (mon->>'id')::integer)
       from jsonb_array_elements(grp->'pokemon') mon)=v_ids limit 1;
  if v_match is not null then
    update public.poke_connections_results set
      solved_tiers=array_append(solved_tiers,v_match->>'tier'),
      completed=(cardinality(solved_tiers)+1=4),updated_at=now()
      where user_id=v_user and challenge_date=v_date;
  else
    update public.poke_connections_results set mistakes=least(4,mistakes+1),
      completed=(mistakes+1>=4),updated_at=now()
      where user_id=v_user and challenge_date=v_date;
  end if;
  return public.poke_connections_today();
end; $$;

revoke execute on function public.poke_connections_today() from public,anon;
